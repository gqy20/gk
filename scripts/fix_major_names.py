def normalize_code(code: str) -> str:
    """统一代码格式：去掉 T/K 后缀用于匹配"""
    return re.sub(r'[TK]$', '', code)


def _lookup(code: str, mapping: dict) -> str | None:
    """双向查找：精确匹配 → 去T/K匹配 → 反向去T/K匹配"""
    # 1. 精确匹配
    v = mapping.get(code)
    if v:
        return v
    # 2. 查询码去 T/K 后匹配
    clean_q = re.sub(r'[TK]$', '', code)
    v = mapping.get(clean_q)
    if v:
        return v
    # 3. 遍历映射表，将 key 去 T/K 后与查询码比较
    for k, v in mapping.items():
        if re.sub(r'[TK]$', '', k) == code:
            return v
    return None


def find_name(zydm: str, category_key: str) -> str | None:
    """根据代码和分类查找专业名称"""
    if category_key == "1050":
        return _lookup(zydm, BENKE_MAP)
    elif category_key == "1070":
        return _lookup(zydm, ZHIJIAO_BENKE_MAP)
    elif category_key == "1060":
        return _lookup(zydm, GAOZHI_ZHUANKE_MAP)
    return None


def main():
    apply_mode = "--apply" in sys.argv

    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    json_path = os.path.join(base_dir, "majors_data.json")

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    total_missing = 0
    total_fixed = 0
    total_not_found = []
    fixes = []

    for cat in data["categories"]:
        cat_key = cat["key"]
        cat_name = cat["name"]
        for ml in cat["门类"]:
            ml_name = ml["name"]
            for cls in ml["专业类"]:
                cls_name = cls["name"]
                for major in cls["专业"]:
                    zydm = major["zydm"]
                    zymc = major.get("zymc", "")
                    if not zymc or zymc == "-":
                        total_missing += 1
                        name = find_name(zydm, cat_key)
                        if name:
                            total_fixed += 1
                            fixes.append({
                                "zydm": zydm,
                                "old": zymc,
                                "new": name,
                                "class": cls_name,
                                "menlei": ml_name,
                                "cat": cat_name,
                            })
                            if apply_mode:
                                major["zymc"] = name
                        else:
                            total_not_found.append({
                                "zydm": zydm,
                                "class": cls_name,
                                "menlei": ml_name,
                                "cat": cat_name,
                                "cat_key": cat_key,
                            })

    # 输出结果
    print(f"=" * 60)
    print(f"专业名称补全报告")
    print(f"=" * 60)
    print(f"\n总缺失数量: {total_missing}")
    print(f"成功匹配:   {total_fixed}")
    print(f"未找到映射: {len(total_not_found)}")
    print()

    if fixes:
        print(f"--- 已匹配的专业 ({total_fixed} 个) ---")
        print(f"{'代码':<10} {'原值':<6} {'新名称':<25} {'专业类':<16} {'门类'}")
        print("-" * 85)
        for fx in fixes:
            print(f"{fx['zydm']:<10} {fx['old']:<6} {fx['new']:<25} {fx['class']:<16} {fx['menlei']}")

    if total_not_found:
        print(f"\n--- 未找到映射的专业 ({len(total_not_found)} 个) ---")
        for nf in total_not_found:
            print(f"  {nf['zydm']} ({nf['class']} / {nf['menlei']} / {nf['cat']} key={nf['cat_key']})")

    if apply_mode:
        backup_path = json_path + ".bak"
        # 备份原文件
        import shutil
        shutil.copy2(json_path, backup_path)
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"\n✅ 已写入 {json_path}")
        print(f"   原文件备份至 {backup_path}")
    else:
        print(f"\n💡 这是预览模式。运行 `python scripts/fix_major_names.py --apply` 实际写入")


