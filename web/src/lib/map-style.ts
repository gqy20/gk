export function getProvincePalette(name: string): ProvincePalette {
  return PROVINCE_PALETTES[name] || fallbackProvincePalette(name);
}

function fallbackProvincePalette(name: string): ProvincePalette {
  let hash = 0;
  for (const char of name) {
    hash = (hash + char.charCodeAt(0)) % FALLBACK_PROVINCE_PALETTES.length;
  }
  return FALLBACK_PROVINCE_PALETTES[hash];
}
